//! `--apps`: the look of the apps outside the shell -- GTK 3 and GTK 4
//! (libadwaita) colours, the Ptyxis terminal palette, and Firefox
//! (userChrome.css, user.js, the Gruvbox theme add-on).
//!
//! The files come from `generator/assets/` (built into the binary). The GTK
//! ones are templates: `{{accent_bg}}`, `{{accent_fg}}` and `{{accent_line}}`
//! are filled in from `color.rs`, so the apps always match the shell.

use std::fs;
use std::path::PathBuf;

use crate::check::Status;
use crate::color::{ACCENT_BG, ACCENT_FG, Palette};
use crate::paths::Paths;
use crate::{firefox, fsutil};

/// Marks a file as generated by this program (so it may be overwritten).
const MARKER: &str = "Generated by gruvbox-shell-theme";
const FIX: &str = "gruvbox-shell-theme --apps";

#[derive(Clone, Copy)]
enum CommentStyle {
    Css,
    Hash,
    DoubleSlash,
}

impl CommentStyle {
    fn line(self, text: &str) -> String {
        match self {
            CommentStyle::Css => format!("/* {text} */\n"),
            CommentStyle::Hash => format!("# {text}\n"),
            CommentStyle::DoubleSlash => format!("// {text}\n"),
        }
    }
}

struct Template {
    what: &'static str,
    /// Relative to generator/, for the header.
    source: &'static str,
    text: &'static str,
    comments: CommentStyle,
}

const GTK3: Template = Template {
    what: "GTK 3 colours",
    source: "assets/gtk/gtk-3.0.css",
    text: include_str!("../assets/gtk/gtk-3.0.css"),
    comments: CommentStyle::Css,
};
const GTK4: Template = Template {
    what: "GTK 4 colours",
    source: "assets/gtk/gtk-4.0.css",
    text: include_str!("../assets/gtk/gtk-4.0.css"),
    comments: CommentStyle::Css,
};
const PTYXIS: Template = Template {
    what: "Ptyxis palette",
    source: "assets/ptyxis/gruvbox-titlebar.palette",
    text: include_str!("../assets/ptyxis/gruvbox-titlebar.palette"),
    comments: CommentStyle::Hash,
};
/// Its id (the file name without extension) is what settings.rs selects.
pub const PTYXIS_PALETTE_ID: &str = "gruvbox-titlebar";
const USER_CHROME: Template = Template {
    what: "Firefox userChrome.css",
    source: "assets/firefox/userChrome.css",
    text: include_str!("../assets/firefox/userChrome.css"),
    comments: CommentStyle::Css,
};
const USER_JS: Template = Template {
    what: "Firefox user.js",
    source: "assets/firefox/user.js",
    text: include_str!("../assets/firefox/user.js"),
    comments: CommentStyle::DoubleSlash,
};

struct AppFile {
    what: &'static str,
    path: PathBuf,
    contents: String,
}

fn files(paths: &Paths) -> Result<Vec<AppFile>, String> {
    let palette = Palette::new()?;
    let vars = [("accent_bg", ACCENT_BG), ("accent_fg", ACCENT_FG), ("accent_line", palette.accent_line.as_str())];
    let mut files = vec![
        render(&GTK3, &vars, paths.gtk3_css.clone())?,
        render(&GTK4, &vars, paths.gtk4_css.clone())?,
        render(&PTYXIS, &vars, paths.ptyxis_palettes_dir.join(format!("{PTYXIS_PALETTE_ID}.palette")))?,
    ];
    for profile in firefox::profiles(paths) {
        files.push(render(&USER_CHROME, &vars, profile.join("chrome/userChrome.css"))?);
        files.push(render(&USER_JS, &vars, profile.join("user.js"))?);
    }
    Ok(files)
}

fn render(template: &Template, vars: &[(&str, &str)], path: PathBuf) -> Result<AppFile, String> {
    let body = fill(template.text, vars).map_err(|e| format!("{}: {e}", template.source))?;
    let header = template.comments.line(&format!(
        "{MARKER} from generator/{}: edit that file and run install.sh, not this one.",
        template.source
    ));
    Ok(AppFile { what: template.what, path, contents: header + &body })
}

/// Replace `{{name}}` placeholders; any placeholder left over is an error.
fn fill(template: &str, vars: &[(&str, &str)]) -> Result<String, String> {
    let mut out = template.to_string();
    for (name, value) in vars {
        out = out.replace(&format!("{{{{{name}}}}}"), value);
    }
    match out.find("{{") {
        Some(start) => {
            let end = out[start..].find("}}").map_or(out.len(), |i| start + i + 2);
            Err(format!("unknown placeholder {}", &out[start..end]))
        }
        None => Ok(out),
    }
}

fn is_ours(bytes: &[u8]) -> bool {
    let head = &bytes[..bytes.len().min(512)];
    String::from_utf8_lossy(head).contains(MARKER)
}

/// Install every file; returns one line per thing done, for the user.
pub fn install(paths: &Paths) -> Result<Vec<String>, String> {
    let mut report = Vec::new();
    for file in files(paths)? {
        let outcome = fsutil::install(&file.path, file.contents.as_bytes(), is_ours)
            .map_err(|e| format!("cannot write {}: {e}", file.path.display()))?;
        report.push(format!("{} ({}): {outcome}", file.what, file.path.display()));
    }
    if firefox::is_installed() {
        let profiles = firefox::profiles(paths);
        if profiles.is_empty() {
            report.push("Firefox: no profile yet -- start Firefox once, close it, and run install.sh again".into());
        } else if !profiles.iter().all(|p| firefox::theme_installed(p)) {
            report.push(format!("Firefox: {}", firefox::offer_theme(paths)?));
        }
    }
    Ok(report)
}

/// For `--check`.
pub fn status(paths: &Paths) -> Vec<Status> {
    let mut statuses = match files(paths) {
        Ok(files) => files
            .iter()
            .map(|f| {
                let current = fs::read(&f.path).is_ok_and(|bytes| bytes == f.contents.as_bytes());
                Status::new(current, format!("{}: up to date ({})", f.what, f.path.display()), FIX)
            })
            .collect(),
        Err(e) => vec![Status::new(false, format!("cannot render the app files: {e}"), "")],
    };
    if firefox::is_installed() {
        let profiles = firefox::profiles(paths);
        if profiles.is_empty() {
            statuses.push(Status::new(false, "Firefox has a profile", "start Firefox once, close it, and run install.sh again"));
        }
        for profile in profiles {
            statuses.push(Status::new(
                firefox::theme_installed(&profile),
                format!("Firefox Gruvbox theme add-on: installed ({})", profile.display()),
                FIX,
            ));
        }
    }
    statuses
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::test_dir;

    #[test]
    fn fill_replaces_known_and_rejects_unknown_placeholders() {
        assert_eq!(fill("a {{x}} {{x}} b", &[("x", "1")]).unwrap(), "a 1 1 b");
        assert_eq!(fill("{{y}} z", &[("x", "1")]).unwrap_err(), "unknown placeholder {{y}}");
    }

    #[test]
    fn every_template_renders_completely() {
        let paths = Paths::for_test(&test_dir("apps-render"));
        let rendered = files(&paths).unwrap();
        assert_eq!(rendered.len(), 3, "GTK 3, GTK 4, Ptyxis (no Firefox profile here)");
        for file in &rendered {
            assert!(is_ours(file.contents.as_bytes()), "{} has the marker", file.what);
            assert!(!file.contents.contains("{{"), "{} fully filled", file.what);
        }
        assert!(rendered[0].contents.contains(&format!("accent_bg_color {ACCENT_BG};")));
    }

    #[test]
    fn firefox_files_go_into_the_profile() {
        let home = test_dir("apps-firefox");
        let root = home.join(".mozilla/firefox");
        fs::create_dir_all(root.join("p.default-release")).unwrap();
        fs::write(root.join("installs.ini"), "[A]\nDefault=p.default-release\n").unwrap();
        let rendered = files(&Paths::for_test(&home)).unwrap();
        let targets: Vec<_> = rendered.iter().skip(3).map(|f| f.path.strip_prefix(&root).unwrap().to_owned()).collect();
        assert_eq!(targets, [PathBuf::from("p.default-release/chrome/userChrome.css"), PathBuf::from("p.default-release/user.js")]);
        assert!(rendered[4].contents.starts_with("// Generated by"));
    }
}
