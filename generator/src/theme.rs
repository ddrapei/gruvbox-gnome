//! The shell stylesheet: rendered from the installed GNOME Shell's stock
//! stylesheet, compared with the installed one, written atomically.
//!
//! There is no cache or stamp file: rendering takes a few milliseconds, so
//! "up to date" simply means "the installed file is exactly what would be
//! written now". Any change -- a GNOME update, an edited colour constant, a
//! new build of this program -- is therefore always picked up.

use std::fs;

use crate::color::Palette;
use crate::fsutil::{tmp_path, write_atomic};
use crate::paths::Paths;
use crate::{css, system};

const GRESOURCE: &str = "/usr/share/gnome-shell/gnome-shell-theme.gresource";
const SOURCE_CSS: &str = "/org/gnome/shell/theme/gnome-shell-dark.css";
/// Testing only: read the stock stylesheet from this plain file instead.
const SOURCE_OVERRIDE_ENV: &str = "GRUVBOX_SHELL_THEME_SOURCE";
const HEADER_START: &str = "/* Generated by ";
const HEADER_END: &str = "*/\n";

/// The recoloured stylesheet (without header) and any non-fatal warnings.
pub struct Rendered {
    pub css: String,
    pub warnings: Vec<String>,
}

pub fn render() -> Result<Rendered, String> {
    let palette = Palette::new()?;
    let source = load_source()?;
    let css = css::recolor(&source, &palette)?;
    let warnings = css::validate(&source, &css)?;
    Ok(Rendered { css, warnings })
}

fn load_source() -> Result<String, String> {
    let bytes = match std::env::var_os(SOURCE_OVERRIDE_ENV) {
        Some(path) => fs::read(&path).map_err(|e| format!("cannot read {}: {e}", path.display()))?,
        None => gio::Resource::load(GRESOURCE)
            .map_err(|e| format!("{GRESOURCE}: {e}"))?
            .lookup_data(SOURCE_CSS, gio::ResourceLookupFlags::NONE)
            .map_err(|e| format!("{SOURCE_CSS}: {e}"))?
            .to_vec(),
    };
    String::from_utf8(bytes).map_err(|e| format!("stock stylesheet is not UTF-8: {e}"))
}

/// Informational comment at the top of the file. Its fields come from outside
/// (a path, another program's output), so they are made comment-safe: a `*/`
/// would end the comment and inject CSS that bypassed the structure check.
fn header(exe: &str, shell_version: &str) -> String {
    let safe = |s: &str| s.replace("*/", "* /").replace(|c: char| c.is_control(), " ");
    format!(
        "{HEADER_START}{} from {SOURCE_CSS}\n * ({}). Do not edit: regenerated automatically\n * when GNOME Shell is updated. {HEADER_END}",
        safe(exe),
        safe(shell_version),
    )
}

/// The installed stylesheet without its header; None if missing or foreign.
fn installed_css(paths: &Paths) -> Option<String> {
    let text = fs::read_to_string(&paths.theme_css).ok()?;
    let rest = text.strip_prefix(HEADER_START)?;
    let end = rest.find(HEADER_END)? + HEADER_END.len();
    Some(rest[end..].to_string())
}

pub fn is_current(paths: &Paths, rendered: &Rendered) -> bool {
    installed_css(paths).as_deref() == Some(rendered.css.as_str())
}

/// Write the stylesheet unless it is already current (or `force`).
/// Returns whether it was written.
pub fn install(paths: &Paths, rendered: &Rendered, force: bool) -> Result<bool, String> {
    if !force && is_current(paths, rendered) {
        return Ok(false);
    }
    let exe = std::env::current_exe().map_or_else(|_| "gruvbox-shell-theme".into(), |p| p.display().to_string());
    let text = header(&exe, &system::shell_version()) + &rendered.css;
    write_atomic(&paths.theme_css, text.as_bytes()).map_err(|e| format!("cannot write {}: {e}", paths.theme_css.display()))?;
    Ok(true)
}

/// Fail-safe: without the stylesheet the extension keeps the stock look, which
/// is always better than a stylesheet that may not match the installed shell.
pub fn remove(paths: &Paths) {
    let _ = fs::remove_file(&paths.theme_css);
    let _ = fs::remove_file(tmp_path(&paths.theme_css));
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::test_dir;

    #[test]
    fn header_cannot_inject_css() {
        let h = header("/evil*/ * { color: red; } /*", "GNOME */\n#x{}");
        assert_eq!(h.matches("*/").count(), 1, "{h}");
        assert!(h.ends_with(HEADER_END));
    }

    #[test]
    fn install_writes_once_then_is_current() {
        let dir = test_dir("theme-install");
        let paths = Paths::for_test(&dir);
        let rendered = Rendered { css: ".a { color: #fff; }\n".into(), warnings: vec![] };
        assert!(!is_current(&paths, &rendered));
        assert!(install(&paths, &rendered, false).unwrap());
        assert!(is_current(&paths, &rendered));
        assert!(!install(&paths, &rendered, false).unwrap(), "unchanged: not rewritten");
        assert!(install(&paths, &rendered, true).unwrap(), "--force rewrites");
        let changed = Rendered { css: ".a { color: #000; }\n".into(), warnings: vec![] };
        assert!(!is_current(&paths, &changed));
        remove(&paths);
        assert!(!paths.theme_css.exists());
    }
}
